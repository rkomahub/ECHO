import numpy as np
from qutip import Qobj, qeye

from echo_spin.control.microwave import (
    logical_axis_carrier_phase,
    microwave_hamiltonian,
)
from echo_spin.control.pulses import sine_envelope
from echo_spin.dynamics.propagators import time_dependent_propagator


def toggling_hamiltonians(
    free_hamiltonian: Qobj,
    pulses: list[Qobj],
) -> list[Qobj]:
    """Return the toggling-frame Hamiltonian for each free interval."""
    cumulative = qeye(free_hamiltonian.dims[0])

    hamiltonians = [free_hamiltonian]

    for pulse in pulses:
        cumulative = pulse * cumulative
        hamiltonians.append(
            cumulative.dag() * free_hamiltonian * cumulative
        )

    return hamiltonians


def toggling_propagator(
    hamiltonians: list[Qobj],
    durations: list[float],
) -> Qobj:
    """Return the propagator generated by consecutive toggling-frame intervals."""
    if len(hamiltonians) != len(durations):
        raise ValueError(
            "hamiltonians and durations must have the same length."
        )

    if not hamiltonians:
        raise ValueError("At least one interval is required.")

    propagator = qeye(hamiltonians[0].dims[0])

    for hamiltonian, duration in zip(hamiltonians, durations):
        interval = (-1j * hamiltonian * duration).expm()
        propagator = interval * propagator

    return propagator


def finite_pulse_propagator(
    free_hamiltonian: Qobj,
    control_operator: Qobj,
    duration: float,
    envelope,
    steps: int,
    start_time: float = 0.0,
) -> Qobj:
    """Propagate a finite pulse with the free Hamiltonian active."""
    if not np.isfinite(duration) or duration <= 0:
        raise ValueError("duration must be finite and positive.")

    if not np.isfinite(start_time):
        raise ValueError("start_time must be finite.")

    def hamiltonian(time):
        return free_hamiltonian + envelope(time) * control_operator

    return time_dependent_propagator(
        hamiltonian=hamiltonian,
        t0=start_time,
        t1=start_time + duration,
        steps=steps,
    )


def finite_pulse_sequence_propagator(
    free_hamiltonian: Qobj,
    durations: list[float],
    pulse_propagators: list[Qobj],
) -> Qobj:
    """Propagate alternating free-evolution intervals and finite pulses."""
    if len(durations) != len(pulse_propagators) + 1:
        raise ValueError(
            "There must be one more free interval than pulse propagators."
        )

    propagator = qeye(free_hamiltonian.dims[0])

    for index, duration in enumerate(durations):
        free_interval = (
            -1j * free_hamiltonian * duration
        ).expm()

        propagator = free_interval * propagator

        if index < len(pulse_propagators):
            propagator = pulse_propagators[index] * propagator

    return propagator


def finite_pulse_intervals(
    pulse_centers: list[float],
    pulse_duration: float,
    total_duration: float,
) -> list[float]:
    """Return free-evolution intervals between finite pulses."""
    if pulse_duration <= 0:
        raise ValueError("pulse_duration must be positive.")

    if total_duration <= 0:
        raise ValueError("total_duration must be positive.")

    if not pulse_centers:
        return [total_duration]

    centers = list(pulse_centers)
    half_duration = pulse_duration / 2

    intervals = [
        centers[0] - half_duration,
    ]

    for previous, current in zip(centers[:-1], centers[1:]):
        intervals.append(
            current - previous - pulse_duration
        )

    intervals.append(
        total_duration - centers[-1] - half_duration
    )

    if any(interval < 0 for interval in intervals):
        raise ValueError(
            "Pulses overlap or extend outside the sequence."
        )

    return intervals


def logical_sine_pulse_propagator(
    free_hamiltonian: Qobj,
    control_operator: Qobj,
    carrier: float,
    transition_element: complex,
    angle: float,
    axis: str,
    duration: float,
    steps: int,
    start_time: float = 0.0,
) -> Qobj:
    """Propagate a calibrated logical-axis sine pulse with absolute carrier timing."""
    if free_hamiltonian.dims != control_operator.dims:
        raise ValueError(
            "Hamiltonian/control dimensions differ: "
            f"{free_hamiltonian.dims} versus {control_operator.dims}."
        )

    for name, operator in [
        ("free_hamiltonian", free_hamiltonian),
        ("control_operator", control_operator),
    ]:
        if not operator.isoper:
            raise ValueError(f"{name} must be a square operator.")

        matrix = operator.full()

        if not np.all(np.isfinite(matrix)):
            raise ValueError(f"{name} must contain finite entries.")

        hermiticity_defect = np.linalg.norm(
            matrix - matrix.conj().T,
            ord="fro",
        )
        scale = np.linalg.norm(matrix, ord="fro")
        tolerance = 1e-10 + 1e-13 * scale

        if hermiticity_defect > tolerance:
            raise ValueError(
                f"{name} is not sufficiently Hermitian: "
                f"defect={hermiticity_defect:.3e}, "
                f"tolerance={tolerance:.3e}."
            )

    if not np.isfinite(carrier) or carrier <= 0:
        raise ValueError("carrier must be finite and positive.")

    if not np.isfinite(angle):
        raise ValueError("angle must be finite.")

    if not np.isfinite(duration) or duration <= 0:
        raise ValueError("duration must be finite and positive.")

    if not np.isfinite(start_time):
        raise ValueError("start_time must be finite.")

    if (
        isinstance(steps, (bool, np.bool_))
        or not isinstance(steps, (int, np.integer))
        or steps <= 0
    ):
        raise ValueError("steps must be a positive integer.")

    phase = logical_axis_carrier_phase(axis, transition_element)

    peak_amplitude = (
        angle * np.pi
        / (
            2 * np.sqrt(2.0)
            * abs(transition_element) * duration
        )
    )
    dt = duration / steps

    def midpoint_hamiltonian(endpoint_time):
        """Evaluate drift and the absolute-time carrier at the interval midpoint."""
        time = endpoint_time - dt / 2

        envelope = sine_envelope(
            time=time - start_time,
            duration=duration,
            peak_amplitude=peak_amplitude,
        )

        microwave = microwave_hamiltonian(
            time=time,
            control=control_operator,
            drives=[{
                "omega": carrier,
                "phase": phase,
                "omega_x": envelope,
                "omega_y": 0.0,
            }],
        )

        return free_hamiltonian + microwave

    return time_dependent_propagator(
        hamiltonian=midpoint_hamiltonian,
        t0=start_time,
        t1=start_time + duration,
        steps=steps,
    )
